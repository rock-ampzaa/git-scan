-- 使用了xmake的 c3lang 扩展 才能正确编译 target[library-obj]. 否则会报错
add_rules("mode.release","mode.debug","mode.releasedbg","mode.minsizerel")
target("library-obj")
        before_build(function(target)
                import("check_c3lib_env", {rootdir=os.getenv("HOME") .. "/.xmake/scripts/"})()
        end)
        set_kind("object")
        set_default(false)
        add_files("scan-git-c3/src/proc.c3")
        add_libdirs(os.getenv("C3LIBRARY_PATH"))
        add_libs("c3git")
        add_links("git2")
        add_links("rock-soo")
        add_links("icuuc")
        add_links("icuio")
target("scan-gitdir")
        set_kind("binary")
        set_default(true)
        add_deps("library-obj")
        add_files("read-dir-list-d/src/*.d")
